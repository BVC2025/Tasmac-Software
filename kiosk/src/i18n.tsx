const STRINGS: Record<Lang, Strings> = { ta, en }

interface LangCtx {
  lang: Lang
  setLang: (l: Lang) => void
  t: Strings
  reason: (code: string | null | undefined) => string
}

const Ctx = createContext<LangCtx | null>(null)

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>('ta')
  const t = STRINGS[lang]
  const reason = (code: string | null | undefined) => t.reasons[code ?? ''] ?? t.reasons.default
  return <Ctx.Provider value={{ lang, setLang, t, reason }}>{children}</Ctx.Provider>
}

export function useLang() {
  const c = useContext(Ctx)
  if (!c) throw new Error('useLang outside LangProvider')
  return c
}
